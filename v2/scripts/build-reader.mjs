// Builds the Study-only Reader and inlines everything into one committed template.
// No dependencies beyond the Node standard library.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const v2 = join(here, '..');
const dist = join(v2, 'dist-reader');
const assetsDir = join(dist, 'assets');
const generatedDir = join(v2, 'src/lib/generated');

function run() {
  console.log('› vite build (reader entry)…');
  execFileSync('npx', ['vite', 'build', '--config', 'vite.config.reader.ts'], {
    cwd: v2,
    stdio: 'inherit',
  });

  const assets = new Map(
    (existsSync(assetsDir) ? readdirSync(assetsDir) : []).map((f) => [f, join(assetsDir, f)]),
  );
  const resolveAsset = (url) => assets.get(basename(url.split('?')[0]));

  let html = readFileSync(join(dist, 'reader.html'), 'utf8');

  // Drop preload hints — the single chunk is inlined, nothing to prefetch.
  html = html.replace(/<link\b[^>]*\brel="modulepreload"[^>]*>\s*/gi, '');

  // Inline the JS chunk. `</script` inside string/regex literals is escaped so the tag never ends early.
  html = html.replace(/<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/gi, (m, src) => {
    const file = resolveAsset(src);
    if (!file) return m;
    const code = readFileSync(file, 'utf8').replace(/<\/script/gi, '<\\/script');
    return `<script type="module">\n${code}\n</script>`;
  });

  // Inline the stylesheet, rewriting KaTeX font refs to woff2 data URIs (D23).
  html = html.replace(/<link\b[^>]*\brel="stylesheet"[^>]*>/gi, (m) => {
    const href = m.match(/href="([^"]+)"/)?.[1];
    const file = href && resolveAsset(href);
    if (!file) return m;
    return `<style>\n${inlineFonts(readFileSync(file, 'utf8'), resolveAsset)}\n</style>`;
  });

  assertPlaceholder(html);
  assertNoExternalRefs(html);

  mkdirSync(generatedDir, { recursive: true });
  const template = `// GENERATED by scripts/build-reader.mjs — do not edit.\nexport const READER_TEMPLATE = ${JSON.stringify(html)};\n`;
  writeFileSync(join(generatedDir, 'reader-template.ts'), template);

  const kb = (Buffer.byteLength(html, 'utf8') / 1024).toFixed(1);
  console.log(`✓ reader-template.ts — ${kb} KB self-contained HTML`);
}

// Keep only the woff2 src (as a data URI); delete the woff/ttf alternates entirely.
function inlineFonts(css, resolveAsset) {
  css = css.replace(/,?\s*url\([^)]*\.(?:woff|ttf)\)\s*format\(["'][^"']*["']\)/gi, '');
  css = css.replace(/,?\s*url\([^)]*\.(?:woff|ttf)\)/gi, '');
  return css.replace(/url\((["']?)([^)"']+\.woff2)\1\)/gi, (m, _q, url) => {
    const file = resolveAsset(url);
    if (!file) throw new Error(`build-reader: woff2 asset not found for ${url}`);
    return `url(data:font/woff2;base64,${readFileSync(file).toString('base64')})`;
  });
}

function assertPlaceholder(html) {
  if (!/<script\b[^>]*\bid="notebook-source"[^>]*>\s*<\/script>/i.test(html)) {
    console.error('build-reader: payload placeholder <script id="notebook-source"></script> missing');
    process.exit(1);
  }
}

// Fail loudly if anything would still hit the network. Script bodies are blanked first so JS/CSS
// string literals (e.g. `src="…"` inside code) never trip the scan.
function assertNoExternalRefs(html) {
  const scan = html.replace(/(<script\b[^>]*>)[\s\S]*?(<\/script>)/gi, '$1$2');
  const offenders = [];
  const external = (v) => v && !v.startsWith('data:') && !v.startsWith('#');

  for (const m of scan.matchAll(/url\(\s*(["']?)([^)"']+)\1\s*\)/gi)) {
    if (external(m[2].trim())) offenders.push(`url(${m[2].trim()})`);
  }
  for (const m of scan.matchAll(/\bsrc=(["'])([^"']*)\1/gi)) {
    if (m[2].trim() && !m[2].trim().startsWith('data:')) offenders.push(`src=${m[2]}`);
  }
  for (const m of scan.matchAll(/\bhref=(["'])([^"']*)\1/gi)) {
    if (external(m[2].trim())) offenders.push(`href=${m[2]}`);
  }
  if (offenders.length) {
    console.error('build-reader: external references remain (must be self-contained):');
    for (const o of offenders.slice(0, 10)) console.error(`  ${o}`);
    process.exit(1);
  }
}

run();
